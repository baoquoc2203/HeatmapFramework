// Robinhood Chain data extractor — run with stock macOS, no install:
//
//   osascript -l JavaScript tools/ro_extract.js
//
// Reads ro-desk.html and ro-signals.html (the upstream pages, copied in verbatim),
// executes their inline scripts against an inert DOM stub so every data constant
// is evaluated exactly as the page itself evaluates it, and writes the result into
// robinhood.html between its RO-DATA markers. Nothing is computed here that the pages do not compute: this
// file only SELECTS fields. Re-run it after every upstream update.
ObjC.import('Foundation');

const ROOT = (() => {                       // repo root = parent of this script's folder
  const a = $.NSProcessInfo.processInfo.arguments.js.map(x => x.js);
  const me = a.find(x => /ro_extract\.js$/.test(x)) || 'tools/ro_extract.js';
  const abs = me.startsWith('/') ? me : $.NSFileManager.defaultManager.currentDirectoryPath.js + '/' + me;
  return abs.replace(/\/tools\/ro_extract\.js$/, '');
})();
const read = p => $.NSString.stringWithContentsOfFileEncodingError(ROOT + '/' + p, $.NSUTF8StringEncoding, null).js;
const write = (p, s) => $(s).writeToFileAtomicallyEncodingError(ROOT + '/' + p, true, $.NSUTF8StringEncoding, null);

// every property is another callable stub, so render code runs and does nothing
const stub = () => new Proxy(function () {}, {
  get: (t, k) => k === Symbol.toPrimitive ? () => '' : k === 'length' ? 0
             : k === Symbol.iterator ? function* () {} : stub(),
  set: () => true, apply: () => stub(), construct: () => stub()
});
function evalPage(file, exportExpr) {
  const html = read(file);
  const src = [...html.matchAll(/<script(?![^>]*\bsrc=)(?![^>]*type="application\/)[^>]*>([\s\S]*?)<\/script>/g)]
    .map(m => m[1]).join('\n;\n');
  const g = {
    document: stub(), localStorage: { getItem: () => null, setItem() {} },
    matchMedia: () => ({ matches: false, addEventListener() {}, addListener() {} }),
    requestAnimationFrame: () => 0, setTimeout: () => 0, clearTimeout() {}, setInterval: () => 0,
    ResizeObserver: function () { return { observe() {}, disconnect() {} }; },
    MutationObserver: function () { return { observe() {} }; },
    IntersectionObserver: function () { return { observe() {} }; },
    getComputedStyle: () => stub(), navigator: stub(), location: stub(), addEventListener() {},
    THREE: stub(), devicePixelRatio: 1, innerWidth: 1280, innerHeight: 800,
    performance: { now: () => 0 }, console: { log() {}, warn() {}, error() {} }
  };
  g.window = g;
  const names = Object.keys(g);
  return new Function(...names, src + '\n;return (' + exportExpr + ');')(...names.map(k => g[k]));
}

const desk = evalPage('ro-desk.html', `({
  date: DATE, session: SESSION, sum: SUM, nav: +NAV.toFixed(2), unreal: +UNREAL.toFixed(2),
  alerts: ALERTS, decide: DECIDE, rules: RULES.slice(0, 4), foot: FOOT,
  navHist: NAV_HIST, paper: PAPER, scored: SCORED,
  closed: CLOSED.map(c => ({ t: c.t, pnl: +c.fills.reduce((s, f) => s - f[3], 0).toFixed(2),
                             last: c.fills[c.fills.length - 1][0], why: c.fills[c.fills.length - 1][1] })),
  btc: { level: BTCV.level, label: ["Ủng hộ","Trung lập","Rủi ro","Báo động"][BTCV.level], price: BTCV.price,
         lv: BTCV.lv, cnt: BTCV.cnt, closes: BTCV.closes, why: BTCV.why, src: BTCV.src },
  pos: POS.map(p => ({ t: p.t, grp: p.grp, slot: p.slot, st: p.st, px: p.px, avg: p.avg, cost: p.cost,
                       val: +p.val.toFixed(4), pnl: +(+p.pnl).toFixed(4), pct: +(+p.pct).toFixed(4),
                       next: p.next, trig: p.trig, dist: +(+p.dist).toFixed(4), lv: p.lv, contract: p.contract || null }))
})`);

const sig = evalPage('ro-signals.html', `({
  date: DATE, lead: LEAD,
  sig: ORDER.filter(s => s.g === 'gy').map(s => {
    const d = (s.det || []).find(x => /contract/i.test(x[0]));
    return { t: s.t, sub: s.sub, px: s.px, ch: s.ch, act: s.act, trig: s.trig, now: s.now || 0,
             st: s.st, lv: s.lv, contract: d ? ((d[1].match(/0x[0-9a-fA-F]{40}/) || [null])[0]) : null };
  }),
  avoid: AVOID.filter(a => /GIẢ/.test(a))
})`);

if (desk.date !== sig.date) throw new Error('ro-desk (' + desk.date + ') and ro-signals (' + sig.date + ') are from different closes');
const hold = desk.pos.reduce((s, p) => s + p.val, 0);
if (Math.abs(hold + desk.sum.cash - desk.nav) > 0.01) throw new Error('positions + cash do not add up to NAV');

// Inject between the markers in robinhood.html so the page stays a single self-contained file.
const page = read('robinhood.html');
const START = '<!-- RO-DATA:START -->', END = '<!-- RO-DATA:END -->';
const i = page.indexOf(START), j = page.indexOf(END);
if (i < 0 || j < i) throw new Error('RO-DATA markers not found in robinhood.html');
const json = JSON.stringify({ desk, sig }).replace(/</g, '\\u003c');   // a "</script>" in a note can never close the tag
const block = START + '\n<script>/* GENERATED by tools/ro_extract.js from ro-desk.html + ro-signals.html — do not edit by hand. */\n'
            + 'window.RO_DATA=' + json + ';</script>\n' + END;
write('robinhood.html', page.slice(0, i) + block + page.slice(j + END.length));
'robinhood.html data updated · close ' + desk.date + ' · ' + desk.pos.length + ' positions · ' + sig.sig.length + ' signals · NAV $' + desk.nav;
